/* Run an external command. Returns 0 on success (exit code 0), -1 otherwise. */
static int
run_cmd(const char *const argv[])
{
    pid_t pid = fork();
    if (pid < 0) return -1;
    if (pid == 0) {
        int devnull = open("/dev/null", O_WRONLY);
        if (devnull >= 0) {
            dup2(devnull, STDOUT_FILENO);
            dup2(devnull, STDERR_FILENO);
            close(devnull);
        }
        execvp(argv[0], (char *const *)argv);
        _exit(127);
    }
    int status = 0;
    while (waitpid(pid, &status, 0) < 0)
        if (errno != EINTR) return -1;
    return (WIFEXITED(status) && WEXITSTATUS(status) == 0) ? 0 : -1;
}

static int
detect_resolvectl(void)
{
    const char *argv[] = {"resolvectl", "status", NULL};
    return run_cmd(argv) == 0 ? 1 : 0;
}

static int
apply_resolvectl(mqvpn_dns_t *dns)
{
    if (dns->tun_name[0] == '\0') {
        LOG_ERR("dns: resolvectl requires TUN interface name");
        return -1;
    }

    /* resolvectl dns <tun> <server1> [server2] ... */
    const char *argv[MQVPN_DNS_MAX_SERVERS + 4];
    int argc = 0;
    argv[argc++] = "resolvectl";
    argv[argc++] = "dns";
    argv[argc++] = dns->tun_name;
    for (int i = 0; i < dns->n_servers; i++)
        argv[argc++] = dns->servers[i];
    argv[argc] = NULL;

    if (run_cmd(argv) < 0) {
        LOG_ERR("dns: resolvectl dns failed");
        return -1;
    }

    /* resolvectl default-route <tun> true */
    const char *dr_argv[] = {"resolvectl", "default-route", dns->tun_name, "true", NULL};
    if (run_cmd(dr_argv) < 0) {
        LOG_WRN("dns: resolvectl default-route failed (continuing)");
    }

    LOG_INF("dns: configured %d server(s) via resolvectl on %s", dns->n_servers,
            dns->tun_name);
    return 0;
}

static void
restore_resolvectl(mqvpn_dns_t *dns)
{
    if (dns->tun_name[0] == '\0') return;
    const char *argv[] = {"resolvectl", "revert", dns->tun_name, NULL};
    if (run_cmd(argv) < 0)
        LOG_WRN("dns: resolvectl revert failed (interface may already be gone)");
    else
        LOG_INF("dns: reverted DNS via resolvectl on %s", dns->tun_name);
}

void
mqvpn_dns_init(mqvpn_dns_t *dns)
{
    memset(dns, 0, sizeof(*dns));
    dns->lock_fd = -1;
    dns->resolv_path = "/etc/resolv.conf";
    dns->backup_path = "/etc/resolv.conf.mqvpn.bak";
    dns->lock_path = "/run/mqvpn-dns.lock";
}

/* First line of every resolv.conf mqvpn writes: how a later run recognises
 * a file left behind by a crash. */
#define MQVPN_RESOLV_MARKER "# Generated by mqvpn"
#define RESOLV_MAX_SIZE     (1u << 20)

/* Read a whole (small) file into a malloc'd NUL-terminated buffer. 0, or -1
 * with errno set. */
static int
read_whole_file(const char *path, char **out, size_t *out_len)
{
    int fd = open(path, O_RDONLY | O_CLOEXEC);
    if (fd < 0) return -1;
    size_t cap = 4096, used = 0;
    char *buf = malloc(cap);
    if (!buf) {
        close(fd);
        errno = ENOMEM;
        return -1;
    }
    for (;;) {
        if (used + 1 >= cap) {
            if (cap >= RESOLV_MAX_SIZE) {
                free(buf);
                close(fd);
                errno = EFBIG;
                return -1;
            }
            char *nb = realloc(buf, cap * 2);
            if (!nb) {
                free(buf);
                close(fd);
                errno = ENOMEM;
                return -1;
            }
            buf = nb;
            cap *= 2;
        }
        ssize_t r = read(fd, buf + used, cap - 1 - used);
        if (r < 0) {
            if (errno == EINTR) continue;
            int e = errno;
            free(buf);
            close(fd);
            errno = e;
            return -1;
        }
        if (r == 0) break;
        used += (size_t)r;
    }
    close(fd);
    buf[used] = '\0';
    *out = buf;
    if (out_len) *out_len = used;
    return 0;
}

/* The file a write to `path` must land in. /etc/resolv.conf is often a
 * symlink (systemd-resolved, NetworkManager, resolvconf): mqvpn has always
 * written through it, leaving the link in place, so the atomic replace
 * below targets the link's destination, never the link itself. */
static int
write_target(const char *path, char *out, size_t out_len)
{
    struct stat st;
    if (lstat(path, &st) != 0 || !S_ISLNK(st.st_mode)) {
        snprintf(out, out_len, "%s", path);
        return 0;
    }
    char *real = realpath(path, NULL);
    if (real) {
        snprintf(out, out_len, "%s", real);
        free(real);
        return 0;
    }
    /* Dangling link: resolve its target by hand (relative to the link). */
    char link[PATH_MAX];
    ssize_t n = readlink(path, link, sizeof(link) - 1);
    if (n <= 0) return -1;
    link[n] = '\0';
    if (link[0] == '/') {
        snprintf(out, out_len, "%s", link);
    } else {
        const char *slash = strrchr(path, '/');
        if (slash)
            snprintf(out, out_len, "%.*s/%s", (int)(slash - path), path, link);
        else
            snprintf(out, out_len, "%s", link);
    }
    return 0;
}

/* Rewrite `target` in place (truncate + write + fsync). Only used when the
 * atomic path cannot work: under the systemd unit's ProtectSystem=strict
 * /etc is read-only except the bind-mounted files themselves, so neither a
 * temp file next to them nor a rename over a mount point is possible. */
static int
write_file_inplace(const char *target, const char *data, size_t len, mode_t mode)
{
    int fd = open(target, O_WRONLY | O_CREAT | O_TRUNC | O_CLOEXEC, mode);
    if (fd < 0) return -1;
    int ok = 1;
    size_t off = 0;
    while (off < len) {
        ssize_t w = write(fd, data + off, len - off);
        if (w < 0) {
            if (errno == EINTR) continue;
            ok = 0;
            break;
        }
        off += (size_t)w;
    }
    if (ok && fsync(fd) != 0) ok = 0;
    int e = errno;
    if (close(fd) != 0 && ok) {
        ok = 0;
        e = errno;
    }
    errno = e;
    return ok ? 0 : -1;
}

/* Replace `path` atomically with `data`: a temp file in the same directory,
 * synced and renamed over the target, so a crash or a full disk never
 * leaves a truncated resolv.conf. Keeps the existing file's mode (0644 for
 * a new one). Falls back to an in-place rewrite when the directory is not
 * writable or the target is a mount point (sandboxed unit). 0, or -1 with
 * errno set (the caller logs). */
static int
write_file_atomic(const char *path, const char *data, size_t len)
{
    char target[PATH_MAX];
    if (write_target(path, target, sizeof(target)) < 0) return -1;

    char tmp[PATH_MAX + 32];
    const char *slash = strrchr(target, '/');
    if (slash)
        snprintf(tmp, sizeof(tmp), "%.*s/.mqvpn-resolv.XXXXXX", (int)(slash - target),
                 target);
    else
        snprintf(tmp, sizeof(tmp), ".mqvpn-resolv.XXXXXX");

    mode_t mode = 0644;
    struct stat st;
    if (stat(target, &st) == 0) mode = st.st_mode & 07777;

    int fd = mkstemp(tmp);
    if (fd < 0) {
        if (errno == EROFS || errno == EACCES || errno == EPERM)
            return write_file_inplace(target, data, len, mode);
        return -1;
    }
    (void)fcntl(fd, F_SETFD, FD_CLOEXEC);
    int ok = fchmod(fd, mode) == 0;
    size_t off = 0;
    while (ok && off < len) {
        ssize_t w = write(fd, data + off, len - off);
        if (w < 0) {
            if (errno == EINTR) continue;
            ok = 0;
            break;
        }
        off += (size_t)w;
    }
    if (ok && fsync(fd) != 0) ok = 0;
    if (close(fd) != 0) ok = 0;
    int renamed = ok && rename(tmp, target) == 0;
    if (!renamed) {
        int e = errno;
        unlink(tmp);
        /* A bind-mounted target (EBUSY) or one on another mount (EXDEV)
         * cannot be renamed over: rewrite it in place instead. */
        if (ok && (e == EBUSY || e == EXDEV))
            return write_file_inplace(target, data, len, mode);
        errno = e;
        return -1;
    }
    return 0;
}

/* 1 when `path` is a resolv.conf written by mqvpn (marker first line). */
static int
is_mqvpn_generated(const char *path)
{
    char *buf = NULL;
    if (read_whole_file(path, &buf, NULL) < 0) return 0;
    int yes = strncmp(buf, MQVPN_RESOLV_MARKER, strlen(MQVPN_RESOLV_MARKER)) == 0;
    free(buf);
    return yes;
}

/* Put the backup back over resolv.conf and drop it. 0, or -1 (backup kept). */
static int
restore_backup(mqvpn_dns_t *dns)
{
    char *buf = NULL;
    size_t len = 0;
    if (read_whole_file(dns->backup_path, &buf, &len) < 0) return -1;
    int rc = write_file_atomic(dns->resolv_path, buf, len);
    free(buf);
    if (rc < 0) return -1;
    unlink(dns->backup_path);
    return 0;
}

static void
release_lock(mqvpn_dns_t *dns, int unlink_path)
{
    if (dns->lock_fd < 0) return;
    close(dns->lock_fd);
    dns->lock_fd = -1;
    if (unlink_path) unlink(dns->lock_path);
}

int
mqvpn_dns_apply(mqvpn_dns_t *dns)
{
    if (dns->n_servers == 0) {
        return 0; /* nothing to do */
    }

    /* Try resolvectl first. Whether it is there is probed once per process:
     * otherwise every reconnect forks a synchronous `resolvectl status`
     * from the event loop. */
    if (dns->resolvectl_probe == 0) dns->resolvectl_probe = detect_resolvectl() ? 1 : -1;
    if (dns->resolvectl_probe > 0) {
        dns->use_resolvectl = 1;
        int rc = apply_resolvectl(dns);
        if (rc == 0) {
            dns->active = 1;
            return 0;
        }
        LOG_WRN("dns: resolvectl failed, falling back to resolv.conf");
        dns->use_resolvectl = 0;
    }

    /* Acquire exclusive lock — prevents multiple mqvpn instances from
     * clobbering each other's resolv.conf backup.  flock() is automatically
     * released by the kernel if the process dies. */
    int lfd = open(dns->lock_path, O_CREAT | O_RDWR | O_CLOEXEC, 0644);
    if (lfd >= 0) {
        if (flock(lfd, LOCK_EX | LOCK_NB) < 0) {
            LOG_ERR("dns: another mqvpn instance is managing DNS (lock: %s)",
                    dns->lock_path);
            close(lfd);
            return -1;
        }
        dns->lock_fd = lfd;
    } else {
        LOG_WRN("dns: could not create lock file %s: %m (continuing without lock)",
                dns->lock_path);
    }

    /* A resolv.conf still carrying our marker next to a backup was left by
     * a run that never restored it (crash, SIGKILL): the backup holds the
     * real original. Put it back first, or the backup below would be
     * overwritten with our own servers and the original lost for good. */
    if (mqvpn_dns_has_stale_backup(dns) && is_mqvpn_generated(dns->resolv_path)) {
        LOG_WRN("dns: %s was left by an earlier mqvpn run, restoring it from %s first",
                dns->resolv_path, dns->backup_path);
        if (restore_backup(dns) < 0) {
            LOG_ERR("dns: failed to restore %s from %s: %m", dns->resolv_path,
                    dns->backup_path);
            release_lock(dns, 0);
            return -1;
        }
    }

    /* Check for systemd-resolved symlink */
    struct stat st;
    if (lstat(dns->resolv_path, &st) == 0 && S_ISLNK(st.st_mode)) {
        LOG_WRN("dns: %s is a symlink (possibly systemd-resolved). "
                "Overwriting anyway.",
                dns->resolv_path);
    }

    /* Backup original resolv.conf */
    char *orig = NULL;
    size_t orig_len = 0;
    if (read_whole_file(dns->resolv_path, &orig, &orig_len) < 0 ||
        write_file_atomic(dns->backup_path, orig, orig_len) < 0) {
        LOG_WRN("dns: could not backup %s (file may not exist)", dns->resolv_path);
        /* Continue anyway — new installation may not have resolv.conf */
    }
    free(orig);

    /* Write new resolv.conf */
    char content[MQVPN_DNS_MAX_SERVERS * 80 + 512];
    int len = snprintf(content, sizeof(content),
                       MQVPN_RESOLV_MARKER " — do not edit\n# Original saved to %s\n",
                       dns->backup_path);
    for (int i = 0; i < dns->n_servers && len > 0 && (size_t)len < sizeof(content); i++)
        len += snprintf(content + len, sizeof(content) - (size_t)len, "nameserver %s\n",
                        dns->servers[i]);
    if (len < 0 || (size_t)len >= sizeof(content) ||
        write_file_atomic(dns->resolv_path, content, (size_t)len) < 0) {
        LOG_ERR("dns: cannot write %s: %m", dns->resolv_path);
        release_lock(dns, 0);
        return -1;
    }

    dns->active = 1;
    LOG_INF("dns: configured %d server(s), backed up to %s", dns->n_servers,
            dns->backup_path);
    return 0;
}

void
mqvpn_dns_restore(mqvpn_dns_t *dns)
{
    if (!dns->active) return;

    if (dns->use_resolvectl) {
        restore_resolvectl(dns);
        dns->active = 0;
        return;
    }

    if (restore_backup(dns) < 0) {
        LOG_ERR("dns: failed to restore %s from %s", dns->resolv_path, dns->backup_path);
    } else {
        LOG_INF("dns: restored %s", dns->resolv_path);
    }

    dns->active = 0;

    /* Always release lock */
    release_lock(dns, 1);
}

int
mqvpn_dns_has_stale_backup(const mqvpn_dns_t *dns)
{
    return access(dns->backup_path, F_OK) == 0;
}

/* Startup recovery (linux_platform_run_client): undo a resolv.conf a crashed
 * run left behind. Only when resolv.conf still carries our marker — if
 * something rewrote it since, the backup is older than what is there now —
 * and only when no other instance holds the DNS lock (its backup is live). */
void
mqvpn_dns_restore_stale(mqvpn_dns_t *dns)
{
    if (!mqvpn_dns_has_stale_backup(dns)) return;
    if (!is_mqvpn_generated(dns->resolv_path)) {
        LOG_INF("dns: ignoring stale backup %s: %s was not written by mqvpn",
                dns->backup_path, dns->resolv_path);
        return;
    }

    int lfd = open(dns->lock_path, O_RDWR | O_CLOEXEC);
    if (lfd >= 0 && flock(lfd, LOCK_EX | LOCK_NB) < 0) {
        close(lfd); /* another instance is managing DNS right now */
        return;
    }

    LOG_WRN("dns: stale backup found at %s, restoring", dns->backup_path);
    if (restore_backup(dns) < 0)
        LOG_ERR("dns: failed to restore from stale backup");
    else
        LOG_INF("dns: restored %s from stale backup", dns->resolv_path);
    if (lfd >= 0) close(lfd);
}
